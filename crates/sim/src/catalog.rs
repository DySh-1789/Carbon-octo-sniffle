/// Playable armored nation.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum Nation {
    Usa,
    Germany,
    Ussr,
}

impl Nation {
    pub const ALL: [Nation; 3] = [Nation::Usa, Nation::Germany, Nation::Ussr];

    pub fn label(self) -> &'static str {
        match self {
            Nation::Usa => "USA",
            Nation::Germany => "GERMANY",
            Nation::Ussr => "USSR",
        }
    }

    pub fn short_tag(self) -> &'static str {
        match self {
            Nation::Usa => "US",
            Nation::Germany => "DE",
            Nation::Ussr => "SU",
        }
    }
}

/// Tactical vehicle role class.
#[derive(Copy, Clone, Debug, PartialEq, Eq, Hash, Serialize, Deserialize)]
pub enum VehicleClass {
    Light,
    Medium,
    Heavy,
    TankDestroyer,
}

impl VehicleClass {
    pub fn short_label(self) -> &'static str {
        match self {
            VehicleClass::Light => "LT",
            VehicleClass::Medium => "MT",
            VehicleClass::Heavy => "HT",
            VehicleClass::TankDestroyer => "TD",
        }
    }

    pub fn label(self) -> &'static str {
        match self {
            VehicleClass::Light => "Light Tank",
            VehicleClass::Medium => "Medium Tank",
            VehicleClass::Heavy => "Heavy Tank",
            VehicleClass::TankDestroyer => "Tank Destroyer",
        }
    }
}

/// Roman numeral display for tiers `1..=8`.
pub fn tier_roman(tier: u8) -> &'static str {
    match tier {
        1 => "I",
        2 => "II",
        3 => "III",
        4 => "IV",
        5 => "V",
        6 => "VI",
        7 => "VII",
        8 => "VIII",
        _ => "?",
    }
}

/// Complete historical specification of a single playable/AI vehicle.
#[derive(Clone, Debug, Serialize, Deserialize)]
pub struct VehicleSpec {
    pub id: String,
    pub name: String,
    pub nation: Nation,
    /// Tech tree rank `1..=8`.
    pub tier: u8,
    pub class: VehicleClass,
    pub mass_tons: f32,
    pub engine_hp: f32,
    pub max_forward_kmh: f32,
    pub max_reverse_kmh: f32,
    pub hull_turn_deg_s: f32,
    pub turret_turn_deg_s: f32,
    pub gun_min_deg: f32,
    pub gun_max_deg: f32,
    /// Limited horizontal traverse arc for casemate TDs (`Some(10.0)` = ±10 deg; `None` = 360 deg).
    pub turret_yaw_limit_deg: Option<f32>,
    pub gun_name: String,
    pub reload_time: f32,
    pub shell: ShellSpec,
    pub armor: ArmorProfile,
    pub blueprint: VoxelTankBlueprint,
}

impl VehicleSpec {
    #[inline]
    pub fn power_to_weight(&self) -> f32 {
        self.engine_hp / self.mass_tons.max(1.0)
    }

    /// Builds the high-detail `0.10 m` bespoke voxel 3D model assembly for this vehicle.
    pub fn build_models(&self) -> TankVoxelModels {
        voxel::build_vehicle_models(&self.id).unwrap_or_else(|| build_tank_models(&self.blueprint))
    }

    /// Converts this historical specification + its voxel model mounts into a simulation [`TankConfig`].
    pub fn to_tank_config(&self, models: &TankVoxelModels) -> TankConfig {
        let hp_t = self.power_to_weight();
        let acceleration = (2.4 + hp_t * 0.22).clamp(3.2, 8.2);
        let vs = TANK_VOXEL_SIZE;
        let hull_half_w = (self.blueprint.hull_w as f32 * vs * 0.5).clamp(1.15, 1.90);
        let hull_half_l = (self.blueprint.hull_l as f32 * vs * 0.5).clamp(2.10, 3.60);
        let hull_radius = (hull_half_w * hull_half_w + hull_half_l * hull_half_l).sqrt();

        TankConfig {
            vehicle_id: self.id.clone(),
            name: self.name.clone(),
            nation: self.nation,
            tier: self.tier,
            class: self.class,
            max_forward_speed: self.max_forward_kmh / 3.6,
            max_reverse_speed: self.max_reverse_kmh / 3.6,
            acceleration,
            brake_decel: 12.0,
            coast_drag: 2.8,
            hull_turn_rate: self.hull_turn_deg_s.to_radians(),
            turret_yaw_rate: self.turret_turn_deg_s.to_radians(),
            turret_yaw_limit: self.turret_yaw_limit_deg.map(f32::to_radians),
            gun_pitch_rate: 0.45,
            gun_min_pitch: self.gun_min_deg.to_radians(),
            gun_max_pitch: self.gun_max_deg.to_radians(),
            reload_time: self.reload_time,
            muzzle_velocity: self.shell.muzzle_velocity,
            shell_drag: self.shell.drag_coeff,
            shell: self.shell.clone(),
            armor: self.armor.clone(),
            hull_radius,
            hull_half_width: hull_half_w,
            hull_half_length: hull_half_l,
            turret_mount_offset: models.turret_mount_offset,
            gun_mount_offset: models.gun_mount_offset,
            muzzle_offset: models.muzzle_offset,
        }
    }
}

/// Complete Stage 5 vehicle catalog (3 nations × 8 tiers = 24 approved vehicles).
#[derive(Clone, Debug)]
pub struct VehicleCatalog {
    vehicles: Vec<VehicleSpec>,
}

impl Default for VehicleCatalog {
    fn default() -> Self {
        Self::stage5_catalog()
    }
}

impl VehicleCatalog {
    pub fn stage5_catalog() -> Self {
        let mut vehicles = Vec::with_capacity(24);
        vehicles.extend(build_usa_vehicles());
        vehicles.extend(build_germany_vehicles());
        vehicles.extend(build_ussr_vehicles());
        Self { vehicles }
    }

    pub fn all(&self) -> &[VehicleSpec] {
        &self.vehicles
    }

    pub fn by_id(&self, id: &str) -> Option<&VehicleSpec> {
        self.vehicles.iter().find(|v| v.id == id)
    }

    pub fn by_nation(&self, nation: Nation) -> Vec<&VehicleSpec> {
        let mut list: Vec<&VehicleSpec> = self
            .vehicles
            .iter()
            .filter(|v| v.nation == nation)
            .collect();
        list.sort_by_key(|v| v.tier);
        list
    }

    pub fn by_tier(&self, tier: u8) -> Vec<&VehicleSpec> {
        self.vehicles.iter().filter(|v| v.tier == tier).collect()
    }

    pub fn by_nation_and_tier(&self, nation: Nation, tier: u8) -> Option<&VehicleSpec> {
        self.vehicles
            .iter()
            .find(|v| v.nation == nation && v.tier == tier)
    }

    /// Default showcase vehicle when opening the Hangar (Tier III M4A1 Sherman).
    pub fn default_vehicle(&self) -> &VehicleSpec {
        self.by_id("us_m4a1").unwrap_or(&self.vehicles[0])
    }
}

fn ap_shell(name: &str, caliber_mm: f32, mass_kg: f32, vel: f32, pen_0m: f32) -> ShellSpec {
    ShellSpec {
        name: name.to_string(),
        kind: ShellKind::Ap,
        caliber_mm,
        mass_kg,
        muzzle_velocity: vel,
        drag_coeff: if caliber_mm >= 100.0 {
            0.032
        } else if caliber_mm >= 75.0 {
            0.038
        } else {
            0.048
        },
        penetration_0m_mm: pen_0m,
        normalization_deg: 4.0,
        ricochet_start_deg: 60.0,
        ricochet_full_deg: 72.0,
        spall_cone_half_angle_deg: if caliber_mm >= 100.0 {
            18.0
        } else if caliber_mm >= 75.0 {
            15.0
        } else {
            12.0
        },
        spall_ray_count: if caliber_mm >= 100.0 {
            12
        } else if caliber_mm >= 75.0 {
            10
        } else {
            7
        },
    }
}

